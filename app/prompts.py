CARD_JSON_SCHEMA = {
    "name": "product_card",
    "strict": True,
    "schema": {
        "type": "object",
        "additionalProperties": False,
        "required": ["data_conflicts", "key_specs", "seo_title", "seo_description", "search_queries", "commercial"],
        "properties": {
            "data_conflicts": {"type": "array", "items": {"type": "string"}},
            "key_specs": {
                "type": "array",
                "items": {
                    "type": "object",
                    "additionalProperties": False,
                    "required": ["name", "value", "source"],
                    "properties": {
                        "name": {"type": "string"},
                        "value": {"type": "string"},
                        "source": {"type": "string"},
                    },
                },
            },
            "seo_title": {"type": "string"},
            "seo_description": {"type": "string"},
            "search_queries": {"type": "array", "items": {"type": "string"}},
            "commercial": {
                "type": "object",
                "additionalProperties": False,
                "required": ["summary", "target_customers", "tasks"],
                "properties": {
                    "summary": {"type": "string"},
                    "target_customers": {"type": "array", "items": {"type": "string"}},
                    "tasks": {"type": "array", "items": {"type": "string"}},
                },
            },
        },
    },
}


def _input_payload(product: ProductInput) -> dict:
    payload = {
        "name": product.name,
        "manufacturer": product.manufacturer or None,
        "product_type": product.product_type or None,
        "category": product.category or None,
        "specs": product.specs,
        "description": product.description or None,
    }
    return {k: v for k, v in payload.items() if v is not None}


def build_user_prompt(product: ProductInput, json_hint: bool = False) -> str:
    data = json.dumps(_input_payload(product), ensure_ascii=False, indent=2)
    parts = [
        "Подготовь черновик карточки товара по данным ниже.",
        f"<INPUT>\n{data}\n</INPUT>",
    ]
    if not product.specs:
        parts.append(f"Внимание: технических характеристик во входных данных нет. Не придумывай их: в key_specs — source=\"text\" только для дословных фрагментов из описания или типа и source=\"none\" со значением «{NO_DATA}», в текстах — без технических значений.")
    if json_hint:
        schema = json.dumps(CARD_JSON_SCHEMA["schema"], ensure_ascii=False)
        parts.append(f"Верни один JSON-объект строго по схеме: {schema}")
    return "\n\n".join(parts)


def build_repair_prompt(issues: list[str]) -> str:
    listed = "\n".join(f"- {issue}" for issue in issues)
    return (
        "Автоматическая проверка нашла проблемы в твоём ответе:\n"
        f"{listed}\n\n"
        "Исправь их и верни полный JSON заново по той же схеме. "
        "Если для исправления нужна информация, которой нет в <INPUT>, — убери утверждение, а не придумывай значение. "
        f"Длины считаются в символах с пробелами: seo_title ≤ {TITLE_MAX}, seo_description {DESCRIPTION_MIN}–{DESCRIPTION_MAX}."
    )
